def _pool_raw(raw: torch.Tensor, factor: int) -> tuple[torch.Tensor, torch.Tensor]:
    if factor > 1:
        raw = pool_square_tokens(raw, factor)
    norm = F.normalize(raw, p=2, dim=-1, eps=1e-8)
    return raw, norm


def build_pair_indices(n_query: int, n_support: int) -> tuple[torch.Tensor, torch.Tensor]:
    # Keep master indices on CPU so they can be copied to multiple devices safely.
    q_idx = torch.arange(n_query, dtype=torch.long).repeat_interleave(n_support)
    s_idx = torch.arange(n_support, dtype=torch.long).repeat(n_query)
    return q_idx, s_idx


@torch.no_grad()
def compute_episode_distances(
    *,
    metric: MetricEncoder,
    metric_device: torch.device,
    flow: FrozenFlowRuntime,
    support_z: torch.Tensor,
    query_z: torch.Tensor,
    support_images_cpu: torch.Tensor,
    episode_n_way: int,
    args,
    hint_seed: Optional[int],
) -> tuple[torch.Tensor, torch.Tensor, dict[str, torch.Tensor]]:
    """Build distance trajectories plus query-level Metric representations for F1.

    Representation outputs are intentionally candidate-order invariant at the F1 level:
      support_class_repr : (N,D), K-shot class prototypes from real supports
      direct_query_repr  : (Q,D), pooled direct query Metric representation
      step_class_repr    : (Q,T,N,D), K-shot mean of candidate-conditioned Flow states

    TemporalDecayHead subsequently uses a permutation-invariant set encoder over N.
    """
    n_support = int(support_z.shape[0])
    n_query = int(query_z.shape[0])
    episode_n_way = int(episode_n_way)
    if episode_n_way < 2:
        raise ValueError(f"episode_n_way must be >=2, got {episode_n_way}")
    expected_support = int(episode_n_way * args.n_shot)
    if n_support != expected_support:
        raise ValueError(
            f"support count={n_support} != episode_n_way*n_shot={expected_support} "
            f"({episode_n_way}*{args.n_shot})"
        )

    q_idx_cpu, s_idx_cpu = build_pair_indices(n_query, n_support)
    n_pairs = int(q_idx_cpu.numel())
    q_idx_m = q_idx_cpu.to(metric_device)
    s_idx_m = s_idx_cpu.to(metric_device)

    s_z_m = support_z.to(metric_device, non_blocking=True)
    q_z_m = query_z.to(metric_device, non_blocking=True)
    s_feat = metric(s_z_m)
    q_feat = metric(q_z_m)
    s_raw, s_norm = _pool_raw(s_feat.raw, args.ot_pool_factor)
    q_raw, q_norm = _pool_raw(q_feat.raw, args.ot_pool_factor)

    # Fixed-size semantic representations used only by F1.
    support_vec = s_raw.float().mean(dim=-2)  # (S,D)
    support_class_repr = support_vec.reshape(
        episode_n_way, args.n_shot, support_vec.shape[-1]
    ).mean(dim=1)
    direct_query_repr = q_raw.float().mean(dim=-2)  # (Q,D)

    fixed_sk = compute_pairwise_dynamic_sk_weights(
        q_raw, s_raw, weight_eps=args.sk_weight_eps
    )
    direct_ot = pairwise_sinkhorn_from_weights(
        q_norm,
        s_norm,
        fixed_sk.query,
        fixed_sk.support,
        reg=args.sinkhorn_reg,
        n_iter=args.sinkhorn_iter,
        normalize_cost_points=False,
    )
    d0_matrix = direct_ot.distance.float()

    target_vision = flow.encode_target_vision(support_images_cpu)
    hint_all = flow.build_hint(
        support_images_cpu,
        stochastic=args.stochastic_hint,
        pure_noise=args.pure_noise_hint,
        seed=hint_seed,
    )
    query_z_flow = query_z.to(flow.device, non_blocking=True)

    support_chunks = []
    last_chunks = []
    path_lengths = []
    step_repr_chunks = []
    chunk = max(int(args.pair_chunk_size), 1)

    for start in range(0, n_pairs, chunk):
        end = min(start + chunk, n_pairs)
        q_idx_c_cpu = q_idx_cpu[start:end]
        s_idx_c_cpu = s_idx_cpu[start:end]
        q_idx_f = q_idx_c_cpu.to(flow.device)
        s_idx_f = s_idx_c_cpu.to(flow.device)
        q_idx_cm = q_idx_c_cpu.to(metric_device)
        s_idx_cm = s_idx_c_cpu.to(metric_device)

        qz = query_z_flow.index_select(0, q_idx_f)
        post_z = flow.generate_post_states(
            qz,
            target_vision=target_vision.index_select(0, s_idx_f),
            hint=hint_all.index_select(0, s_idx_f),
            num_steps=args.num_steps,
            solver=args.solver,
        )

        b, t = post_z.shape[:2]
        flat_post_m = post_z.reshape(b * t, *post_z.shape[2:]).to(
            metric_device, non_blocking=True
        )
        post_feat = metric(flat_post_m)
        post_raw = post_feat.raw.reshape(
            b, t, post_feat.raw.shape[-2], post_feat.raw.shape[-1]
        )
        if args.ot_pool_factor > 1:
            post_raw = pool_square_tokens(post_raw, args.ot_pool_factor)
        post_norm = F.normalize(post_raw, p=2, dim=-1, eps=1e-8)
        step_repr_chunks.append(post_raw.float().mean(dim=-2))  # (B,T,D)

        s_norm_pair = s_norm.index_select(0, s_idx_cm).unsqueeze(1)
        wq = fixed_sk.query[q_idx_cm, s_idx_cm].unsqueeze(1)
        ws = fixed_sk.support[q_idx_cm, s_idx_cm].unsqueeze(1)

        post_ot = aligned_sinkhorn_from_weights(
            post_norm,
            s_norm_pair,
            wq,
            ws,
            reg=args.sinkhorn_reg,
            n_iter=args.sinkhorn_iter,
            normalize_cost_points=False,
        )
        d_post = post_ot.distance.float()
        d0 = d0_matrix[q_idx_cm, s_idx_cm].unsqueeze(1)
        support_chunks.append(torch.cat([d0, d_post], dim=1))

        q_raw0 = q_raw.index_select(0, q_idx_cm)
        raw_states = torch.cat([q_raw0.unsqueeze(1), post_raw], dim=1)

        if args.trajectory_score_mode == "step_to_last":
            state_norm = F.normalize(raw_states, p=2, dim=-1, eps=1e-8)
            last_norm = state_norm[:, -1:, :, :]
            to_last_ot = aligned_sinkhorn_from_weights(
                state_norm,
                last_norm,
                wq,
                wq,
                reg=args.sinkhorn_reg,
                n_iter=args.sinkhorn_iter,
                normalize_cost_points=False,
            )
            last_chunks.append(to_last_ot.distance.float().clamp_min(0.0))
        else:
            to_last_ot = None

        node_step = (raw_states[:, 1:] - raw_states[:, :-1]).norm(dim=-1)
        path_len = (node_step * wq).sum(dim=-1).sum(dim=-1)
        path_lengths.append(path_len)

        del post_z, flat_post_m, post_feat, post_raw, post_norm, post_ot
        if to_last_ot is not None:
            del to_last_ot

    pair_support = torch.cat(support_chunks, dim=0)
    pair_support = pair_support.reshape(n_query, n_support, args.num_steps + 1)
    support_distances = pair_support.reshape(
        n_query, episode_n_way, args.n_shot, args.num_steps + 1
    )

    if args.trajectory_score_mode == "step_to_support":
        selected_distances = support_distances
    elif args.trajectory_score_mode == "step_to_last":
        pair_last = torch.cat(last_chunks, dim=0)
        pair_last = pair_last.reshape(n_query, n_support, args.num_steps + 1)
        selected_distances = pair_last.reshape(
            n_query, episode_n_way, args.n_shot, args.num_steps + 1
        )
    else:
        raise ValueError(f"unknown trajectory_score_mode={args.trajectory_score_mode}")

    pair_step_repr = torch.cat(step_repr_chunks, dim=0)  # (Q*S,T,D)
    pair_step_repr = pair_step_repr.reshape(
        n_query, n_support, args.num_steps, pair_step_repr.shape[-1]
    )
    step_class_repr = pair_step_repr.reshape(
        n_query, episode_n_way, args.n_shot, args.num_steps, pair_step_repr.shape[-1]
    ).mean(dim=2).permute(0, 2, 1, 3).contiguous()  # (Q,T,N,D)

    path_length = torch.cat(path_lengths).mean() if path_lengths else support_distances.new_zeros(())
    return support_distances, selected_distances, {
        "d0_mean": d0_matrix.mean(),
        "path_length": path_length,
        "support_class_repr": support_class_repr.detach(),
        "direct_query_repr": direct_query_repr.detach(),
        "step_class_repr": step_class_repr.detach(),
    }


@torch.no_grad()
def compute_episode_batch_distances(
    *,
    metric: MetricEncoder,
    metric_device: torch.device,
    flow: FrozenFlowRuntime,
    support_z_batch: torch.Tensor,
    query_z_batch: torch.Tensor,
    support_images_cpu_batch: torch.Tensor,
    episode_n_way: int,
    args,
    hint_seed: Optional[int],
) -> tuple[torch.Tensor, torch.Tensor, dict[str, torch.Tensor]]:
    """True multi-episode version of ``compute_episode_distances``.

    All episodes must share the fixed ImageNet pretrain width (N-way/K-shot/Q-query).
    RAE latents have already been encoded in one batch before this function.  Here:

      * support/query MetricEncoder passes are batched across episodes;
      * Dynamic-SK is still computed independently inside each episode (no leakage);
      * all episode-local query-support pairs are flattened into one global pair stream;
      * DiT/Flow runs over that merged stream using ``pair_chunk_size``;
      * tensors are reshaped back to episode-local N-way/K-shot structure before soft-min.

    The returned leading dimension is B*Q so the existing F1/loss code can operate
    without changing class semantics.
    """
    if support_z_batch.ndim < 3 or query_z_batch.ndim < 3:
        raise ValueError("support_z_batch/query_z_batch must include batch and item dimensions")
    batch_size = int(support_z_batch.shape[0])
    if batch_size < 1 or int(query_z_batch.shape[0]) != batch_size:
        raise ValueError("invalid/mismatched episode batch dimension")
    n_support = int(support_z_batch.shape[1])
    n_query = int(query_z_batch.shape[1])
    episode_n_way = int(episode_n_way)
    expected_support = int(episode_n_way * args.n_shot)
    if n_support != expected_support:
        raise ValueError(
            f"support count={n_support} != episode_n_way*n_shot={expected_support}"
        )
    if n_query != int(args.n_query):
        raise ValueError(f"query count={n_query} != args.n_query={args.n_query}")

    # ------------------------------------------------------------------
    # One MetricEncoder pass for all real supports and all direct queries.
    # ------------------------------------------------------------------
    flat_support_z = support_z_batch.reshape(
        batch_size * n_support, *support_z_batch.shape[2:]
    ).to(metric_device, non_blocking=True)
    flat_query_z = query_z_batch.reshape(
        batch_size * n_query, *query_z_batch.shape[2:]
    ).to(metric_device, non_blocking=True)

    s_feat = metric(flat_support_z)
    q_feat = metric(flat_query_z)
    s_raw_flat, s_norm_flat = _pool_raw(s_feat.raw, args.ot_pool_factor)
    q_raw_flat, q_norm_flat = _pool_raw(q_feat.raw, args.ot_pool_factor)
    n_nodes = int(s_raw_flat.shape[-2])
    repr_dim = int(s_raw_flat.shape[-1])
    s_raw = s_raw_flat.reshape(batch_size, n_support, n_nodes, repr_dim)
    s_norm = s_norm_flat.reshape(batch_size, n_support, n_nodes, repr_dim)
    q_raw = q_raw_flat.reshape(batch_size, n_query, n_nodes, repr_dim)
    q_norm = q_norm_flat.reshape(batch_size, n_query, n_nodes, repr_dim)

    support_vec = s_raw.float().mean(dim=-2)  # B,S,D
    support_class_repr_b = support_vec.reshape(
        batch_size, episode_n_way, args.n_shot, repr_dim
    ).mean(dim=2)  # B,N,D
    direct_query_repr_b = q_raw.float().mean(dim=-2)  # B,Q,D

    # Dynamic-SK must remain episode-local.  This loop is small/cheap compared with
    # DiT generation and deliberately prevents any cross-episode matching.
    fixed_qw_list = []
    fixed_sw_list = []
    d0_list = []
    for bidx in range(batch_size):
        fixed_sk = compute_pairwise_dynamic_sk_weights(
            q_raw[bidx], s_raw[bidx], weight_eps=args.sk_weight_eps
        )
        direct_ot = pairwise_sinkhorn_from_weights(
            q_norm[bidx],
            s_norm[bidx],
            fixed_sk.query,
            fixed_sk.support,
            reg=args.sinkhorn_reg,
            n_iter=args.sinkhorn_iter,
            normalize_cost_points=False,
        )
        fixed_qw_list.append(fixed_sk.query)
        fixed_sw_list.append(fixed_sk.support)
        d0_list.append(direct_ot.distance.float())

    fixed_qw = torch.stack(fixed_qw_list, dim=0)  # B,Q,S,P
    fixed_sw = torch.stack(fixed_sw_list, dim=0)  # B,Q,S,P
    d0_batch = torch.stack(d0_list, dim=0)         # B,Q,S

    # ------------------------------------------------------------------
    # Encode all support conditioning images once, then merge all episode-local
    # pairs into one global Flow stream.  Pair indices never cross episodes.
    # ------------------------------------------------------------------
    flat_support_images_cpu = support_images_cpu_batch.reshape(
        batch_size * n_support, *support_images_cpu_batch.shape[2:]
    )
    target_vision = flow.encode_target_vision(flat_support_images_cpu)
    hint_all = flow.build_hint(
        flat_support_images_cpu,
        stochastic=args.stochastic_hint,
        pure_noise=args.pure_noise_hint,
        seed=hint_seed,
    )
    query_z_flow = query_z_batch.reshape(
        batch_size * n_query, *query_z_batch.shape[2:]
    ).to(flow.device, non_blocking=True)

    ep_idx = torch.arange(batch_size, dtype=torch.long).view(batch_size, 1, 1)
    ep_idx = ep_idx.expand(batch_size, n_query, n_support)
    q_local = torch.arange(n_query, dtype=torch.long).view(1, n_query, 1)
    q_local = q_local.expand(batch_size, n_query, n_support)
    s_local = torch.arange(n_support, dtype=torch.long).view(1, 1, n_support)
    s_local = s_local.expand(batch_size, n_query, n_support)
    q_global_cpu = (ep_idx * n_query + q_local).reshape(-1)
    s_global_cpu = (ep_idx * n_support + s_local).reshape(-1)
    n_pairs = int(q_global_cpu.numel())

    fixed_qw_flat = fixed_qw.reshape(n_pairs, n_nodes)
    fixed_sw_flat = fixed_sw.reshape(n_pairs, n_nodes)
    d0_flat = d0_batch.reshape(n_pairs)
    s_norm_global = s_norm.reshape(batch_size * n_support, n_nodes, repr_dim)
    q_raw_global = q_raw.reshape(batch_size * n_query, n_nodes, repr_dim)

    support_chunks = []
    last_chunks = []
    path_lengths = []
    step_repr_chunks = []
    chunk = max(int(args.pair_chunk_size), 1)

    for start in range(0, n_pairs, chunk):
        end = min(start + chunk, n_pairs)
        qg_cpu = q_global_cpu[start:end]
        sg_cpu = s_global_cpu[start:end]
        qg_f = qg_cpu.to(flow.device)
        sg_f = sg_cpu.to(flow.device)
        qg_m = qg_cpu.to(metric_device)
        sg_m = sg_cpu.to(metric_device)

        qz = query_z_flow.index_select(0, qg_f)
        post_z = flow.generate_post_states(
            qz,
            target_vision=target_vision.index_select(0, sg_f),
            hint=hint_all.index_select(0, sg_f),
            num_steps=args.num_steps,
            solver=args.solver,
        )

        cb, t_steps = post_z.shape[:2]
        flat_post_m = post_z.reshape(cb * t_steps, *post_z.shape[2:]).to(
            metric_device, non_blocking=True
        )
        post_feat = metric(flat_post_m)
        post_raw = post_feat.raw.reshape(
            cb, t_steps, post_feat.raw.shape[-2], post_feat.raw.shape[-1]
        )
        if args.ot_pool_factor > 1:
            post_raw = pool_square_tokens(post_raw, args.ot_pool_factor)
        post_norm = F.normalize(post_raw, p=2, dim=-1, eps=1e-8)
        step_repr_chunks.append(post_raw.float().mean(dim=-2))

        s_norm_pair = s_norm_global.index_select(0, sg_m).unsqueeze(1)
        wq = fixed_qw_flat[start:end].to(metric_device).unsqueeze(1)
        ws = fixed_sw_flat[start:end].to(metric_device).unsqueeze(1)

        post_ot = aligned_sinkhorn_from_weights(
            post_norm,
            s_norm_pair,
            wq,
            ws,
            reg=args.sinkhorn_reg,
            n_iter=args.sinkhorn_iter,
            normalize_cost_points=False,
        )
        d_post = post_ot.distance.float()
        d0 = d0_flat[start:end].to(metric_device).unsqueeze(1)
        support_chunks.append(torch.cat([d0, d_post], dim=1))

        q_raw0 = q_raw_global.index_select(0, qg_m)
        raw_states = torch.cat([q_raw0.unsqueeze(1), post_raw], dim=1)

        if args.trajectory_score_mode == "step_to_last":
            state_norm = F.normalize(raw_states, p=2, dim=-1, eps=1e-8)
            last_norm = state_norm[:, -1:, :, :]
            to_last_ot = aligned_sinkhorn_from_weights(
                state_norm,
                last_norm,
                wq,
                wq,
                reg=args.sinkhorn_reg,
                n_iter=args.sinkhorn_iter,
                normalize_cost_points=False,
            )
            last_chunks.append(to_last_ot.distance.float().clamp_min(0.0))
        else:
            to_last_ot = None

        node_step = (raw_states[:, 1:] - raw_states[:, :-1]).norm(dim=-1)
        path_len = (node_step * wq).sum(dim=-1).sum(dim=-1)
        path_lengths.append(path_len)

        del post_z, flat_post_m, post_feat, post_raw, post_norm, post_ot
        if to_last_ot is not None:
            del to_last_ot

    pair_support = torch.cat(support_chunks, dim=0).reshape(
        batch_size, n_query, n_support, args.num_steps + 1
    )
    support_distances = pair_support.reshape(
        batch_size * n_query, episode_n_way, args.n_shot, args.num_steps + 1
    )

    if args.trajectory_score_mode == "step_to_support":
        selected_distances = support_distances
    elif args.trajectory_score_mode == "step_to_last":
        pair_last = torch.cat(last_chunks, dim=0).reshape(
            batch_size, n_query, n_support, args.num_steps + 1
        )
        selected_distances = pair_last.reshape(
            batch_size * n_query, episode_n_way, args.n_shot, args.num_steps + 1
        )
    else:
        raise ValueError(f"unknown trajectory_score_mode={args.trajectory_score_mode}")

    pair_step_repr = torch.cat(step_repr_chunks, dim=0).reshape(
        batch_size, n_query, n_support, args.num_steps, repr_dim
    )
    step_class_repr_b = pair_step_repr.reshape(
        batch_size, n_query, episode_n_way, args.n_shot, args.num_steps, repr_dim
    ).mean(dim=3).permute(0, 1, 3, 2, 4).contiguous()  # B,Q,T,N,D
    step_class_repr = step_class_repr_b.reshape(
        batch_size * n_query, args.num_steps, episode_n_way, repr_dim
    )

    support_class_repr = support_class_repr_b[:, None].expand(
        batch_size, n_query, episode_n_way, repr_dim
    ).reshape(batch_size * n_query, episode_n_way, repr_dim)
    direct_query_repr = direct_query_repr_b.reshape(batch_size * n_query, repr_dim)

    path_length = (
        torch.cat(path_lengths).mean()
        if path_lengths else support_distances.new_zeros(())
    )
    return support_distances, selected_distances, {
        "d0_mean": d0_batch.mean(),
        "path_length": path_length,
        "support_class_repr": support_class_repr.detach(),
        "direct_query_repr": direct_query_repr.detach(),
        "step_class_repr": step_class_repr.detach(),
        "episode_batch_size": batch_size,
    }


def all_reduce_epoch_stats(stats: "EpochStats", device: torch.device) -> "EpochStats":
    """Sum raw epoch accumulators across ranks before deriving averages."""
    if not (dist.is_available() and dist.is_initialized()):
        return stats

    scalar_names = [
        "loss", "final_ce", "relative_loss", "decay_smooth_loss",
        "final_correct", "direct_correct", "endpoint_correct", "oracle_any_correct",
        "rescue", "degradation", "gamma_sum", "gamma_count", "path_length",
        "relative_reward_std", "relative_best_gain", "relative_abs_delta_gamma",
        "relative_active_fraction", "relative_batches", "queries", "episodes",
    ]
    values = [float(getattr(stats, name)) for name in scalar_names]
    values.extend(float(x) for x in stats.per_step_correct)
    values.extend(float(x) for x in stats.per_step_gamma_sum)
    values.extend(float(x) for x in stats.per_state_weight_sum)
    packed = torch.tensor(values, dtype=torch.float64, device=device)
    dist.all_reduce(packed, op=dist.ReduceOp.SUM)
    out = packed.cpu().tolist()

    int_fields = {
        "final_correct", "direct_correct", "endpoint_correct", "oracle_any_correct",
        "rescue", "degradation", "gamma_count", "relative_batches", "queries", "episodes",
    }
    pos = 0
    for name in scalar_names:
        value = out[pos]
        setattr(stats, name, int(round(value)) if name in int_fields else float(value))
        pos += 1
    n = len(stats.per_step_correct)
    stats.per_step_correct = [int(round(x)) for x in out[pos:pos+n]]
    pos += n
    n = len(stats.per_step_gamma_sum)
    stats.per_step_gamma_sum = [float(x) for x in out[pos:pos+n]]
    pos += n
    n = len(stats.per_state_weight_sum)
    stats.per_state_weight_sum = [float(x) for x in out[pos:pos+n]]
    return stats


