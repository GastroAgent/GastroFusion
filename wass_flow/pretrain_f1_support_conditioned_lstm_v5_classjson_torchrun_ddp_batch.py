    if missing or unexpected:
        raise RuntimeError(
            "M2 -> F1-v5 MetricEncoder mismatch.\n"
            f"missing={missing[:20]}\nunexpected={unexpected[:20]}"
        )
    log_shot_tau = m2_ckpt.get("log_shot_tau", 0.1)
    log_cls_tau = m2_ckpt.get("log_cls_tau", 0.1)
    if log_shot_tau is None or log_cls_tau is None:
        log_shot_tau = log_cls_tau = 0.1
        print("Set log_shot_tau and log_cls_tau is 0.1")
    shot_tau = torch.as_tensor(log_shot_tau, dtype=torch.float32, device=device).reshape(()).exp()
    cls_tau = torch.as_tensor(log_cls_tau, dtype=torch.float32, device=device).reshape(()).exp()
    return shot_tau.detach(), cls_tau.detach()


