@dataclass(frozen=True)
class DistributedContext:
    enabled: bool
    rank: int
    local_rank: int
    world_size: int


def init_distributed() -> DistributedContext:
    world_size = int(os.environ.get("WORLD_SIZE", "1"))
    rank = int(os.environ.get("RANK", "0"))
    local_rank = int(os.environ.get("LOCAL_RANK", "0"))
    enabled = world_size > 1
    if enabled:
        if not torch.cuda.is_available():
            raise RuntimeError("torchrun DDP requires CUDA/NCCL")
        if local_rank >= torch.cuda.device_count():
            raise RuntimeError(
                f"LOCAL_RANK={local_rank}, visible CUDA devices={torch.cuda.device_count()}"
            )
        torch.cuda.set_device(local_rank)
        dist.init_process_group(backend="nccl", init_method="env://")
        rank = dist.get_rank()
        world_size = dist.get_world_size()
    return DistributedContext(enabled, rank, local_rank, world_size)


def is_main_process() -> bool:
    return not (dist.is_available() and dist.is_initialized()) or dist.get_rank() == 0


def rank_print(*args, **kwargs) -> None:
    if is_main_process():
        print(*args, **kwargs)


def unwrap_model(module: nn.Module) -> nn.Module:
    return module.module if isinstance(module, DDP) else module


def distributed_barrier() -> None:
    if dist.is_available() and dist.is_initialized():
        dist.barrier()


def cleanup_distributed() -> None:
    if dist.is_available() and dist.is_initialized():
        dist.destroy_process_group()


def local_episode_budget(global_episodes: int, world_size: int, label: str) -> int:
    if int(global_episodes) < 1:
        raise ValueError(f"{label} must be >=1")
    local = int(math.ceil(int(global_episodes) / max(int(world_size), 1)))
    effective = local * max(int(world_size), 1)
    if effective != int(global_episodes) and is_main_process():
        print(
            f"[F1-v5][DDP][WARN] {label}={global_episodes} not divisible by world_size={world_size}; "
            f"using {local}/rank => effective global {effective}."
        )
    return local


def seed_everything(seed: int) -> None:
    random.seed(int(seed))
    torch.manual_seed(int(seed))
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(int(seed))


def _validate_cuda_device(device: torch.device) -> None:
    if device.type != "cuda":
        return
    if not torch.cuda.is_available():
        raise RuntimeError(f"CUDA device requested but CUDA is unavailable: {device}")
    idx = 0 if device.index is None else int(device.index)
    if idx >= torch.cuda.device_count():
        raise RuntimeError(
            f"requested {device}, but only {torch.cuda.device_count()} CUDA device(s) are visible"
        )


def resolve_devices(
    args, dist_ctx: Optional[DistributedContext] = None
) -> tuple[torch.device, torch.device, torch.device]:
    if not torch.cuda.is_available():
        raise RuntimeError("CUDA is required")

    # torchrun/DDP: one rank owns one GPU; keep all frozen modules and F1 on it.
    if dist_ctx is not None and dist_ctx.enabled:
        d = torch.device("cuda", int(dist_ctx.local_rank))
        _validate_cuda_device(d)
        torch.cuda.set_device(d)
        return d, d, d

    n_gpu = torch.cuda.device_count()
    metric = torch.device("cuda:0" if args.metric_device == "auto" else args.metric_device)
    flow_default = "cuda:1" if n_gpu >= 2 else "cuda:0"
    flow = torch.device(flow_default if args.flow_device == "auto" else args.flow_device)
    rae = torch.device(str(metric) if args.rae_device == "auto" else args.rae_device)
    for d in (metric, flow, rae):
        _validate_cuda_device(d)
        if d.type != "cuda":
            raise RuntimeError("metric_device, flow_device and rae_device must be CUDA")
    torch.cuda.set_device(metric)
    return metric, flow, rae


def _unique_cuda_devices(*devices: torch.device) -> list[torch.device]:
    out: list[torch.device] = []
    seen = set()
    for d in devices:
        if d.type != "cuda":
            continue
        idx = 0 if d.index is None else int(d.index)
        if idx not in seen:
            out.append(torch.device("cuda", idx))
            seen.add(idx)
    return out


def reset_peak_memory(*devices: torch.device) -> None:
    for d in _unique_cuda_devices(*devices):
        torch.cuda.reset_peak_memory_stats(d)


def cuda_memory_report(label: str, *, metric_device, flow_device, rae_device) -> None:
    role_map: dict[int, list[str]] = {}
    for role, d in (("metric/head", metric_device), ("flow/vision", flow_device), ("rae", rae_device)):
        idx = 0 if d.index is None else int(d.index)
        role_map.setdefault(idx, []).append(role)
    parts = []
    for idx, roles in sorted(role_map.items()):
        d = torch.device("cuda", idx)
        peak_alloc = torch.cuda.max_memory_allocated(d) / (1024 ** 3)
        peak_res = torch.cuda.max_memory_reserved(d) / (1024 ** 3)
        now_alloc = torch.cuda.memory_allocated(d) / (1024 ** 3)
        parts.append(
            f"cuda:{idx}[{'+'.join(roles)}] now={now_alloc:.2f}G "
            f"peak_alloc={peak_alloc:.2f}G peak_reserved={peak_res:.2f}G"
        )
    print(f"[F1-v3][MEM][{label}] " + " | ".join(parts))


