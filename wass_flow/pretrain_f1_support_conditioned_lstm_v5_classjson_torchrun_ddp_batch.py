@dataclass
class EpochStats:
    loss: float = 0.0
    final_ce: float = 0.0
    relative_loss: float = 0.0
    decay_smooth_loss: float = 0.0
    final_correct: int = 0
    direct_correct: int = 0
    endpoint_correct: int = 0
    oracle_any_correct: int = 0
    rescue: int = 0
    degradation: int = 0
    gamma_sum: float = 0.0
    gamma_count: int = 0
    path_length: float = 0.0
    relative_reward_std: float = 0.0
    relative_best_gain: float = 0.0
    relative_abs_delta_gamma: float = 0.0
    relative_active_fraction: float = 0.0
    relative_batches: int = 0
    queries: int = 0
    episodes: int = 0
    per_step_correct: list[int] = field(default_factory=list)
    per_step_gamma_sum: list[float] = field(default_factory=list)
    per_state_weight_sum: list[float] = field(default_factory=list)


def run_epoch(
    *,
    decay_head: TemporalDecayHead,
    metric: MetricEncoder,
    metric_device: torch.device,
    flow: FrozenFlowRuntime,
    rae,
    rae_device: torch.device,
    pool: Optional[dict[str, list[str]]],
    manifest_records: Optional[list[EpisodeManifestRecord]],
    transform,
    rng: random.Random,
    n_episodes: int,
    shot_tau: torch.Tensor,
    cls_tau: torch.Tensor,
    args,
    training: bool,
    epoch_index: int,
    optimizer=None,
) -> dict[str, object]:
    decay_head.train(training)
    metric.eval()
    if hasattr(rae, "eval"):
        rae.eval()

    stats = EpochStats(
        per_step_correct=[0 for _ in range(args.num_steps + 1)],
        per_step_gamma_sum=[0.0 for _ in range(args.num_steps)],
        per_state_weight_sum=[0.0 for _ in range(args.num_steps + 1)],
    )

    use_manifest = manifest_records is not None
    if use_manifest == (pool is not None):
        raise ValueError("run_epoch must provide exactly one of pool / manifest_records")

    manifest_order: list[int] = []
    if use_manifest:
        if not manifest_records:
            raise RuntimeError("manifest_records is empty")
        manifest_order = list(range(len(manifest_records)))
        rng.shuffle(manifest_order)

    relative_sigma = relative_sigma_for_epoch(args, epoch_index) if training else 0.0

    episode_batch_size = max(int(args.episode_batch_size), 1)
    if use_manifest and episode_batch_size > 1:
        raise ValueError(
            "episode_batch_size>1 is implemented for fixed-width class-pool/ImageNet pretraining only; "
            "manifest episodes may have variable ways and are intentionally kept unbatched."
        )
    n_batches = int(math.ceil(n_episodes / episode_batch_size))

    for batch_idx in range(n_batches):
        batch_start = batch_idx * episode_batch_size
        current_bs = min(episode_batch_size, n_episodes - batch_start)
        episode_plans: list[EpisodePlan] = []

        for local_b in range(current_bs):
            episode_step = batch_start + local_b
            if use_manifest:
                cycle_pos = episode_step % len(manifest_order)
                if episode_step > 0 and cycle_pos == 0:
                    rng.shuffle(manifest_order)
                record = manifest_records[manifest_order[cycle_pos]]
                ep: EpisodePlan = sample_manifest_episode(
                    record,
                    n_shot=args.n_shot,
                    n_query=args.n_query,
                    rng=rng,
                )
            else:
                ep = sample_episode(
                    pool,
                    n_way=args.n_way,
                    n_shot=args.n_shot,
                    n_query=args.n_query,
                    rng=rng,
                )
            episode_plans.append(ep)

        episode_ways = [len(ep.classes) for ep in episode_plans]
        if any(w < 2 for w in episode_ways):
            raise RuntimeError(f"episode batch contains invalid candidate ways={episode_ways}")
        if len(set(episode_ways)) != 1:
            raise RuntimeError(
                f"true episode batching requires fixed N-way within a batch, got {episode_ways}"
            )
        episode_n_way = int(episode_ways[0])

        support_img_list = []
        query_img_list = []
        query_labels = []
        for ep in episode_plans:
            support_img_cpu, query_img_cpu = load_episode_images(ep, transform)
            support_img_list.append(support_img_cpu)
            query_img_list.append(query_img_cpu)
            if not (0 <= int(ep.query_label) < episode_n_way):
                raise RuntimeError(
                    f"query_label={ep.query_label} out of range for episode_n_way={episode_n_way}"
                )
            query_labels.append(int(ep.query_label))

        # True image batch: B episodes are stacked and encoded by RAE together.
        support_img_cpu_batch = torch.stack(support_img_list, dim=0)  # B,S,C,H,W
        query_img_cpu_batch = torch.stack(query_img_list, dim=0)      # B,Q,C,H,W
        ns = episode_n_way * args.n_shot
        if support_img_cpu_batch.shape[1] != ns:
            raise RuntimeError(
                f"support image count={support_img_cpu_batch.shape[1]} != N*K={ns}"
            )
        if query_img_cpu_batch.shape[1] != int(args.n_query):
            raise RuntimeError(
                f"query image count={query_img_cpu_batch.shape[1]} != n_query={args.n_query}"
            )

        all_img_cpu_batch = torch.cat(
            [support_img_cpu_batch, query_img_cpu_batch], dim=1
        )
        flat_all_img_rae = all_img_cpu_batch.reshape(
            current_bs * (ns + args.n_query), *all_img_cpu_batch.shape[2:]
        ).to(rae_device, non_blocking=True)
        with torch.no_grad():
            flat_latent = encode_rae_chunked(rae, flat_all_img_rae, args.rae_chunk_size)
        latent_batch = flat_latent.reshape(
            current_bs, ns + args.n_query, *flat_latent.shape[1:]
        )
        support_z_batch = latent_batch[:, :ns].detach()
        query_z_batch = latent_batch[:, ns:].detach()

        # B episode labels; each sampled episode currently shares one query class for all Q.
        target = torch.tensor(
            query_labels, device=metric_device, dtype=torch.long
        ).repeat_interleave(int(args.n_query))

        # Validation gets a deterministic batch-level hint stream every epoch.
        hint_seed = None if training else rng.randrange(0, 2**31 - 1)

        if current_bs == 1:
            support_distances, selected_distances, aux = compute_episode_distances(
                metric=metric,
                metric_device=metric_device,
                flow=flow,
                support_z=support_z_batch[0],
                query_z=query_z_batch[0],
                support_images_cpu=support_img_cpu_batch[0],
                episode_n_way=episode_n_way,
                args=args,
                hint_seed=hint_seed,
            )
        else:
            support_distances, selected_distances, aux = compute_episode_batch_distances(
                metric=metric,
                metric_device=metric_device,
                flow=flow,
                support_z_batch=support_z_batch,
                query_z_batch=query_z_batch,
                support_images_cpu_batch=support_img_cpu_batch,
                episode_n_way=episode_n_way,
                args=args,
                hint_seed=hint_seed,
            )

        # Frozen deployable observables. Direct-Support is the anchor for both score modes.
        with torch.no_grad():
            _, selected_step_logits = shot_softmin_class_scores(
                selected_distances, shot_tau=shot_tau, cls_tau=cls_tau
            )
            direct_logits = direct_support_logits(
                support_distances, shot_tau=shot_tau, cls_tau=cls_tau
            )
            features = build_observable_step_features(
                selected_distances,
                selected_step_logits,
                direct_logits,
                eps=args.feature_eps,
                ratio_clip=args.feature_ratio_clip,
            )

        if training:
            optimizer.zero_grad(set_to_none=True)

        raw_decay_logits, gamma = decay_head(
            features.detach(),
            aux["support_class_repr"].detach(),
            aux["direct_query_repr"].detach(),
            aux["step_class_repr"].detach(),
        )
        state_weights = decay_gamma_to_state_weights(gamma)
        _, _, final_logits = weighted_pair_class_logits(
            selected_distances.detach(),
            state_weights,
            shot_tau=shot_tau,
            cls_tau=cls_tau,
        )
        final_ce = F.cross_entropy(final_logits.float(), target)
        smooth_loss = decay_smoothness_loss(gamma)

        relative_loss = raw_decay_logits.new_zeros(())
        rel_stats = {
            "sigma": 0.0,
            "reward_std": 0.0,
            "best_gain_over_current_ce": 0.0,
            "mean_abs_delta_gamma": 0.0,
            "active_fraction": 0.0,
        }
        if training and relative_sigma > 0.0 and float(args.lambda_relative) > 0.0:
            relative_loss, rel_stats = group_relative_decay_loss(
                decay_head=decay_head,
                raw_logits=raw_decay_logits,
                deterministic_gamma=gamma,
                deterministic_logits=final_logits.detach(),
                selected_distances=selected_distances.detach(),
                direct_logits=direct_logits.detach(),
                target=target,
                shot_tau=shot_tau,
                cls_tau=cls_tau,
                sigma=relative_sigma,
                args=args,
            )

        loss = (
            final_ce
            + float(args.lambda_decay_smooth) * smooth_loss
            + float(args.lambda_relative) * relative_loss
        )

        if training:
            loss.backward()
            torch.nn.utils.clip_grad_norm_(decay_head.parameters(), args.grad_clip)
            optimizer.step()

        with torch.no_grad():
            direct_pred = direct_logits.argmax(dim=-1)
            endpoint_pred = selected_step_logits[:, -1].argmax(dim=-1)
            final_pred = final_logits.argmax(dim=-1)
            d_ok = direct_pred.eq(target)
            e_ok = endpoint_pred.eq(target)
            f_ok = final_pred.eq(target)

            per_step_ok = []
            for t in range(args.num_steps + 1):
                ok = selected_step_logits[:, t].argmax(dim=-1).eq(target)
                per_step_ok.append(ok)
                stats.per_step_correct[t] += int(ok.sum().item())
            oracle_any = torch.cat(
                [d_ok.unsqueeze(1), torch.stack(per_step_ok, dim=1)], dim=1
            ).any(dim=1)

            qn = int(target.numel())
            stats.loss += float(loss.detach().item()) * qn
            stats.final_ce += float(final_ce.detach().item()) * qn
            stats.relative_loss += float(relative_loss.detach().item()) * qn
            stats.decay_smooth_loss += float(smooth_loss.detach().item()) * qn
            stats.final_correct += int(f_ok.sum().item())
            stats.direct_correct += int(d_ok.sum().item())
            stats.endpoint_correct += int(e_ok.sum().item())
            stats.oracle_any_correct += int(oracle_any.sum().item())
            stats.rescue += int((~d_ok & f_ok).sum().item())
            stats.degradation += int((d_ok & ~f_ok).sum().item())
            stats.gamma_sum += float(gamma.sum().item())
            stats.gamma_count += int(gamma.numel())
            stats.path_length += float(aux["path_length"].item()) * qn
            stats.queries += qn
            stats.episodes += int(current_bs)

            gamma_step_mean = gamma.mean(dim=0)
            weight_step_mean = state_weights.mean(dim=0)
            for t in range(args.num_steps):
                stats.per_step_gamma_sum[t] += float(gamma_step_mean[t].item()) * qn
            for t in range(args.num_steps + 1):
                stats.per_state_weight_sum[t] += float(weight_step_mean[t].item()) * qn

            if training and relative_sigma > 0.0:
                stats.relative_reward_std += float(rel_stats["reward_std"]) * qn
                stats.relative_best_gain += float(rel_stats["best_gain_over_current_ce"]) * qn
                stats.relative_abs_delta_gamma += float(rel_stats["mean_abs_delta_gamma"]) * qn
                stats.relative_active_fraction += float(rel_stats["active_fraction"]) * qn
                stats.relative_batches += qn

        if (
            training and is_main_process() and args.log_every > 0
            and (batch_idx + 1) % args.log_every == 0
        ):
            print(
                f"  [batch {batch_idx+1:04d}/{n_batches}; ep_bs={current_bs}] "
                f"loss={float(loss.detach()):.4f} ce={float(final_ce.detach()):.4f} "
                f"final/direct/end={int(f_ok.sum())}/{int(d_ok.sum())}/{int(e_ok.sum())} "
                f"gamma={float(gamma.mean().detach()):.3f} "
                f"w_last={float(state_weights[:, -1].mean().detach()):.4f} "
                f"rel_sigma={relative_sigma:.3f} rel_std={rel_stats['reward_std']:.4f}"
            )

        del (
            support_img_cpu_batch, query_img_cpu_batch, all_img_cpu_batch,
            flat_all_img_rae, flat_latent, latent_batch, support_z_batch,
            query_z_batch, support_distances, selected_distances,
            selected_step_logits, features, direct_logits, raw_decay_logits,
            gamma, state_weights, final_logits
        )

    stats = all_reduce_epoch_stats(stats, metric_device)
    qn = max(stats.queries, 1)
    gamma_n = max(stats.gamma_count, 1)
    rel_n = max(stats.relative_batches, 1)
    return {
        "loss": stats.loss / qn,
        "final_ce": stats.final_ce / qn,
        "relative_loss": stats.relative_loss / qn,
        "decay_smooth_loss": stats.decay_smooth_loss / qn,
        "final_accuracy": stats.final_correct / qn,
        "direct_accuracy": stats.direct_correct / qn,
        "endpoint_accuracy": stats.endpoint_correct / qn,
        "oracle_any_accuracy": stats.oracle_any_correct / qn,
        "rescue_count": stats.rescue,
        "degradation_count": stats.degradation,
        "net_rescue": stats.rescue - stats.degradation,
        "gamma_mean": stats.gamma_sum / gamma_n,
        "path_length": stats.path_length / qn,
        "relative_sigma": relative_sigma,
        "relative_reward_std": stats.relative_reward_std / rel_n,
        "relative_best_gain_over_current_ce": stats.relative_best_gain / rel_n,
        "relative_mean_abs_delta_gamma": stats.relative_abs_delta_gamma / rel_n,
        "relative_active_fraction": stats.relative_active_fraction / rel_n,
        "per_step_accuracy": [x / qn for x in stats.per_step_correct],
        "per_step_gamma_mean": [x / qn for x in stats.per_step_gamma_sum],
        "per_state_weight_mean": [x / qn for x in stats.per_state_weight_sum],
        "queries": stats.queries,
        "episodes": stats.episodes,
    }


# -----------------------------------------------------------------------------
# Main
# -----------------------------------------------------------------------------


def main() -> None:
    args = parse_args()
    dist_ctx = init_distributed()
    # Different ranks sample different online episodes/augmentations/noise.
    seed_everything(args.seed + dist_ctx.rank * 100_003)
    metric_device, flow_device, rae_device = resolve_devices(args, dist_ctx)

    m2_ckpt = _torch_load(args.m2_checkpoint, "cpu")
    if not isinstance(m2_ckpt, dict):
        raise ValueError("M2 checkpoint must be a dict")
    resolve_from_m2(args, m2_ckpt)

    if args.n_way < 2 or args.n_shot < 1 or args.n_query < 1:
        raise ValueError("invalid episode settings")
    if args.episode_batch_size < 1:
        raise ValueError("episode_batch_size must be >=1")
    if args.num_steps < 1 or args.pair_chunk_size < 1:
        raise ValueError("num_steps/pair_chunk_size must be >=1")
    if args.ot_pool_factor < 0:
        raise ValueError("ot_pool_factor must be >=0 (0/1=no pooling; >1=spatial pooling)")
    if args.utility_hidden_dim < 1 or args.utility_proj_dim < 1 or args.utility_condition_dim < 1:
        raise ValueError("utility_hidden_dim/utility_proj_dim/utility_condition_dim must be >=1")
    if not 0.0 <= args.utility_head_dropout < 1.0:
        raise ValueError("utility_head_dropout must be in [0,1)")
    if args.feature_ratio_clip <= 0:
        raise ValueError("feature_ratio_clip must be >0")
    if not 0.0 < args.gamma_min < args.gamma_init < 1.0:
        raise ValueError("require 0 < gamma_min < gamma_init < 1")
    if args.lambda_decay_smooth < 0 or args.lambda_relative < 0:
        raise ValueError("lambda_decay_smooth/lambda_relative must be >=0")
    if args.relative_group_size < 2 or args.relative_group_size % 2 != 0:
        raise ValueError("relative_group_size must be an even integer >=2")
    if args.relative_warmup_epochs < 0:
        raise ValueError("relative_warmup_epochs must be >=0")
    if args.relative_sigma_start < 0 or args.relative_sigma_end < 0:
        raise ValueError("relative sigma values must be >=0")
    if args.relative_sigma_start < args.relative_sigma_end:
        raise ValueError("relative_sigma_start should be >= relative_sigma_end for annealing")
    if args.relative_target_step < 0 or args.relative_adv_clip <= 0:
        raise ValueError("invalid relative optimization settings")

    os.makedirs(args.output_dir, exist_ok=True)

    # ------------------------------------------------------------------
    # ImageNet/class-JSON data protocol.
    # Each JSON file is one class pool.  Train and validation both sample
    # fixed-width N-way K-shot Q-query episodes online.
    # ------------------------------------------------------------------
    train_pool = load_class_pool(None, args.train_class_json_root)
    train_pool = filter_episode_classes(
        train_pool, n_shot=args.n_shot, n_query=args.n_query
    )
    val_pool = load_class_pool(None, args.val_class_json_root)
    val_pool = filter_episode_classes(
        val_pool, n_shot=args.n_shot, n_query=args.n_query
    )

    if len(train_pool) < args.n_way:
        raise RuntimeError(
            f"train valid classes={len(train_pool)} < n_way={args.n_way}; "
            f"root={args.train_class_json_root}"
        )
    if len(val_pool) < args.n_way:
        raise RuntimeError(
            f"val valid classes={len(val_pool)} < n_way={args.n_way}; "
            f"root={args.val_class_json_root}"
        )

    train_manifest_records = None
    val_manifest_records = None
    train_data_mode = "class_pool_json_online"
    val_data_mode = "class_pool_json_online"
    train_way_values = [int(args.n_way)]
    val_way_values = [int(args.n_way)]

    train_transform = build_transform(args.image_size, augment=args.augment)
    val_transform = build_transform(args.image_size, augment=False)

    # Frozen RAE.
    torch.cuda.set_device(rae_device)
    rae = build_rae(args.project_root, rae_device)
    if hasattr(rae, "eval"):
        rae.eval()
    if hasattr(rae, "parameters"):
        for p in rae.parameters():
            p.requires_grad_(False)

    # Frozen Flow / EndoViT.
    torch.cuda.set_device(flow_device)
    flow = FrozenFlowRuntime(
        project_root=args.project_root,
        checkpoint=args.dit_checkpoint,
        device=flow_device,
        dit_variant=args.dit_variant,
        num_classes=args.num_classes,
        image_size=args.image_size,
        use_ema=args.use_ema,
        hint_signal_ratio=args.hint_signal_ratio,
        allow_condition_mismatch=args.allow_condition_mismatch,
        amp=args.amp,
    )
    args.hint_signal_ratio = flow.hint_signal_ratio

    # Frozen M2 MetricEncoder + frozen M2 aggregation temperatures.
    torch.cuda.set_device(metric_device)
    metric = MetricEncoder(
        in_dim=1024,
        hidden_dim=args.hidden_dim,
        out_dim=args.metric_dim,
        dropout=args.dropout,
    ).to(metric_device)
    shot_tau, cls_tau = load_m2_metric_and_temperatures(metric, m2_ckpt, metric_device)
    shot_tau = torch.tensor(0.10, dtype=torch.float32, device=metric_device)
    del m2_ckpt
    metric.eval()
    for p in metric.parameters():
        p.requires_grad_(False)

    decay_head = TemporalDecayHead(
        stat_feature_dim=len(FEATURE_NAMES),
        repr_dim=args.metric_dim,
        hidden_dim=args.utility_hidden_dim,
        set_dim=args.utility_proj_dim,
        condition_dim=args.utility_condition_dim,
        head_dropout=args.utility_head_dropout,
        gamma_min=args.gamma_min,
        gamma_init=args.gamma_init,
    ).to(metric_device)

    optimizer = torch.optim.AdamW(
        decay_head.parameters(), lr=args.utility_lr, weight_decay=args.weight_decay
    )
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(
        optimizer, T_max=max(args.epochs, 1), eta_min=0.0
    )

    start_epoch = 0
    if args.resume_checkpoint:
        start_epoch = resume_f1v4(
            decay_head, optimizer, scheduler, args.resume_checkpoint
        )

    if dist_ctx.enabled:
        decay_head = DDP(
            decay_head,
            device_ids=[dist_ctx.local_rank],
            output_device=dist_ctx.local_rank,
            broadcast_buffers=False,
            find_unused_parameters=False,
            gradient_as_bucket_view=True,
        )

    n_head_params = sum(
        p.numel() for p in unwrap_model(decay_head).parameters() if p.requires_grad
    )
    rank_print("=" * 118)
    rank_print("[F1-v5 PRETRAIN] SUPPORT-CONDITIONED LSTM + CLASS-JSON EPISODES + MONOTONIC DYNAMIC DECAY + GROUP-RELATIVE EXPLORATION")
    rank_print(f"train data mode = {train_data_mode}; candidate ways = {train_way_values}")
    rank_print(f"val data mode   = {val_data_mode}; candidate ways = {val_way_values}")
    rank_print(
        f"train episode = {args.n_way}-way {args.n_shot}-shot "
        f"{args.n_query}-query(total), sampled online from train class-JSON pool; "
        f"true episode_batch_size/rank={args.episode_batch_size}"
    )
    rank_print(
        f"val episode   = {args.n_way}-way {args.n_shot}-shot "
        f"{args.n_query}-query(total), sampled online from val class-JSON pool "
        "with a fixed RNG stream each epoch"
    )
    rank_print(
        f"devices: metric/head={metric_device}, flow/vision={flow_device}, rae={rae_device} "
        f"(visible GPUs={torch.cuda.device_count()})"
    )
    rank_print(f"DiT = frozen ({flow.loaded_dit_key}), solver={args.solver}, steps={args.num_steps}")
    rank_print("MetricEncoder = frozen M2; shot_tau/cls_tau = frozen M2")
    rank_print(
        "OT = t0 Dynamic-SK masses fixed across trajectory + "
        "L2-normalized squared-Euclidean + Sinkhorn"
    )
    ot_nodes = 256 if args.ot_pool_factor <= 1 else 256 // (args.ot_pool_factor ** 2)
    rank_print(
        f"Sinkhorn reg={args.sinkhorn_reg}, iter={args.sinkhorn_iter}, "
        f"ot_pool_factor={args.ot_pool_factor}, nodes={ot_nodes}"
    )
    rank_print(f"trajectory score mode = {args.trajectory_score_mode}")
    rank_print(f"observable features ({len(FEATURE_NAMES)}) = {FEATURE_NAMES}")
    rank_print(
        f"TemporalDecayHead = MetricSet(Support)->c0; DirectMetric->h0; MetricSet(step)->x_t; "
        f"Stats(F{len(FEATURE_NAMES)})+Time->conditional LSTM gates; "
        f"Set{args.utility_proj_dim}/Cond{args.utility_condition_dim}/H{args.utility_hidden_dim}->shared MLP->gamma_t, "
        f"dropout={args.utility_head_dropout:g}, params={n_head_params}"
    )
    rank_print(
        f"gamma_t in [{args.gamma_min:g},1), init={args.gamma_init:g}; "
        "u0=1, ut=prod(gamma_1..gamma_t), w=normalize(u) => strict w0>=...>=wT"
    )
    rank_print(
        f"loss = finalCE + {args.lambda_decay_smooth:g}*decaySmooth "
        f"+ {args.lambda_relative:g}*relativeExplore"
    )
    rank_print(
        f"relative exploration: antithetic G={args.relative_group_size}, "
        f"warmup={args.relative_warmup_epochs} epoch(s), "
        f"sigma {args.relative_sigma_start:g}->{args.relative_sigma_end:g}, "
        f"target_step={args.relative_target_step:g}"
    )
    rank_print("reward = CE_direct - CE_perturbed; group-relative standardized per query")
    rank_print("validation/inference = deterministic; NO perturbation / oracle / GT feature")
    rank_print("=" * 118)

    if args.log_cuda_memory and is_main_process():
        reset_peak_memory(metric_device, flow_device, rae_device)
        cuda_memory_report(
            "after-load",
            metric_device=metric_device,
            flow_device=flow_device,
            rae_device=rae_device,
        )

    best_acc = -1.0
    best_degradation = 10**18
    best_ce = float("inf")
    val_seed = args.seed + 17_000_003
    train_episodes_local = local_episode_budget(
        args.episodes_per_epoch, dist_ctx.world_size, "episodes_per_epoch"
    )
    val_episodes_local = local_episode_budget(
        args.val_episodes, dist_ctx.world_size, "val_episodes"
    )
    rank_print(
        f"[F1-v5][DDP] world_size={dist_ctx.world_size}; "
        f"train={args.episodes_per_epoch} global -> {train_episodes_local}/rank; "
        f"val={args.val_episodes} global -> {val_episodes_local}/rank; "
        f"episode_batch_size={args.episode_batch_size}/rank => "
        f"global episode batch/update~{args.episode_batch_size * dist_ctx.world_size}"
    )

    for epoch in range(start_epoch, args.epochs):
        rank_print(f"\n[F1-v5][Epoch {epoch+1}/{args.epochs}]")
        if args.log_cuda_memory and is_main_process():
            reset_peak_memory(metric_device, flow_device, rae_device)

        train_rng = random.Random(
            args.seed + epoch * 1_000_003 + dist_ctx.rank * 10_007
        )
        # Fixed per-rank validation stream => deterministic global validation each epoch.
        val_rng = random.Random(val_seed + dist_ctx.rank * 10_007)

        train_metrics = run_epoch(
            decay_head=decay_head,
            metric=metric,
            metric_device=metric_device,
            flow=flow,
            rae=rae,
            rae_device=rae_device,
            pool=train_pool,
            manifest_records=train_manifest_records,
            transform=train_transform,
            rng=train_rng,
            n_episodes=train_episodes_local,
            shot_tau=shot_tau,
            cls_tau=cls_tau,
            args=args,
            training=True,
            epoch_index=epoch,
            optimizer=optimizer,
        )
        val_metrics = run_epoch(
            decay_head=decay_head,
            metric=metric,
            metric_device=metric_device,
            flow=flow,
            rae=rae,
            rae_device=rae_device,
            pool=val_pool,
            manifest_records=None,
            transform=val_transform,
            rng=val_rng,
            n_episodes=val_episodes_local,
            shot_tau=shot_tau,
            cls_tau=cls_tau,
            args=args,
            training=False,
            epoch_index=epoch,
        )
        scheduler.step()

        rank_print(
            f"[F1-v5][{epoch+1:03d}/{args.epochs}] "
            f"train final/direct/end/oracle="
            f"{100*train_metrics['final_accuracy']:.2f}/"
            f"{100*train_metrics['direct_accuracy']:.2f}/"
            f"{100*train_metrics['endpoint_accuracy']:.2f}/"
            f"{100*train_metrics['oracle_any_accuracy']:.2f}% "
            f"loss={train_metrics['loss']:.4f} gamma={train_metrics['gamma_mean']:.3f} "
            f"rel_sigma={train_metrics['relative_sigma']:.3f} | "
            f"val final/direct/end/oracle="
            f"{100*val_metrics['final_accuracy']:.2f}/"
            f"{100*val_metrics['direct_accuracy']:.2f}/"
            f"{100*val_metrics['endpoint_accuracy']:.2f}/"
            f"{100*val_metrics['oracle_any_accuracy']:.2f}% "
            f"R/D/N={val_metrics['rescue_count']}/{val_metrics['degradation_count']}/"
            f"{val_metrics['net_rescue']} gamma={val_metrics['gamma_mean']:.3f}"
        )
        rank_print(
            "  val per-step acc    = "
            + str([round(100*x, 2) for x in val_metrics["per_step_accuracy"]])
        )
        rank_print(
            "  val gamma_t mean    = "
            + str([round(x, 4) for x in val_metrics["per_step_gamma_mean"]])
        )
        rank_print(
            "  val state w_t mean  = "
            + str([round(x, 4) for x in val_metrics["per_state_weight_mean"]])
        )
        rank_print(
            "  train relative      = "
            f"reward_std={train_metrics['relative_reward_std']:.5f}, "
            f"best_dCE={train_metrics['relative_best_gain_over_current_ce']:.5f}, "
            f"|dGamma|={train_metrics['relative_mean_abs_delta_gamma']:.5f}, "
            f"active={100*train_metrics['relative_active_fraction']:.1f}%"
        )

        if is_main_process():
            save_f1v4_checkpoint(
                os.path.join(args.output_dir, "f1_dynamic_decay_last.pt"),
                metric=metric,
                decay_head=decay_head,
                optimizer=optimizer,
                scheduler=scheduler,
                shot_tau=shot_tau,
                cls_tau=cls_tau,
                epoch=epoch + 1,
                args=args,
                val_metrics=val_metrics,
            )

        acc = float(val_metrics["final_accuracy"])
        deg = int(val_metrics["degradation_count"])
        ce = float(val_metrics["final_ce"])
        better = (
            acc > best_acc + 1e-12
            or (
                abs(acc - best_acc) <= 1e-12
                and (deg < best_degradation or (deg == best_degradation and ce < best_ce))
            )
        )
        if better:
            best_acc, best_degradation, best_ce = acc, deg, ce
            if is_main_process():
                save_f1v4_checkpoint(
                    os.path.join(args.output_dir, "f1_dynamic_decay_best.pt"),
                    metric=metric,
                    decay_head=decay_head,
                    optimizer=optimizer,
                    scheduler=scheduler,
                    shot_tau=shot_tau,
                    cls_tau=cls_tau,
                    epoch=epoch + 1,
                    args=args,
                    val_metrics=val_metrics,
                )
            rank_print(
                f"[F1-v5] new best: final_acc={100*best_acc:.2f}% "
                f"degradation={best_degradation} final_ce={best_ce:.4f}"
            )

        if args.log_cuda_memory and is_main_process():
            cuda_memory_report(
                f"epoch-{epoch+1}",
                metric_device=metric_device,
                flow_device=flow_device,
                rae_device=rae_device,
            )

    if is_main_process():
        design_path = os.path.join(args.output_dir, "f1_dynamic_decay_design.json")
        with open(design_path, "w", encoding="utf-8") as f:
            json.dump(
                {
                    "stage": "F1-v5-support-conditioned-lstm-dynamic-decay-relative-classjson-pretrain",
                    "principle": (
                        "Each support-conditioned LSTM time step predicts a local information-retention gamma_t; "
                        "cumulative products create strictly non-increasing normalized state weights."
                    ),
                    "feature_names": FEATURE_NAMES,
                    "representation_input": {
                        "space": "metric",
                        "support": "K-shot class prototypes -> permutation-invariant set encoder -> c0",
                        "direct_query": "pooled direct query Metric -> h0",
                        "step": "candidate-conditioned K-shot class prototypes -> permutation-invariant set encoder -> x_t",
                        "statistics_time": "independent condition stream into all LSTM gates",
                        "simple_concat": False,
                        "causal": True
                    },
                    "trainable_module": "TemporalDecayHead(Support-c0 + DirectQuery-h0 + MetricStep-x + Stat/Time-conditioned LSTM + shared MLP)",
                    "trainable_params": n_head_params,
                    "trajectory_score_mode": args.trajectory_score_mode,
                    "gamma_min": args.gamma_min,
                    "gamma_init": args.gamma_init,
                    "weight_formula": "u0=1; ut=prod_i<=t gamma_i; wt=ut/sum_j uj",
                    "strict_monotonic_state_weights": True,
                    "optimization": {
                        "main": "exact differentiable final classification CE",
                        "smooth": "adjacent -log(gamma_t) smoothness",
                        "relative": "antithetic group-relative ES-style perturbation distillation",
                        "reward": "CE_direct-CE_perturbed_policy",
                        "lambda_relative": args.lambda_relative,
                        "group_size": args.relative_group_size,
                        "warmup_epochs": args.relative_warmup_epochs,
                        "sigma_start": args.relative_sigma_start,
                        "sigma_end": args.relative_sigma_end,
                    },
                    "train_data_mode": train_data_mode,
                    "train_class_json_root": args.train_class_json_root,
                    "train_candidate_ways": train_way_values,
                    "val_data_mode": val_data_mode,
                    "val_class_json_root": args.val_class_json_root,
                    "val_candidate_ways": val_way_values,
                    "gt_is_model_input": False,
                    "inference_is_deterministic_given_trajectory": True,
                    "devices": {
                        "metric_device": str(metric_device),
                        "flow_device": str(flow_device),
                        "rae_device": str(rae_device),
                    },
                },
                f,
                ensure_ascii=False,
                indent=2,
            )

    distributed_barrier()
    cleanup_distributed()

if __name__ == "__main__":
    main()
