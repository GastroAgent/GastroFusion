def resume_f1v4(
    decay_head: TemporalDecayHead,
    optimizer,
    scheduler,
    path: str,
) -> int:
    ckpt = _torch_load(path, "cpu")
    if ckpt.get("stage") != "F1-v5-support-conditioned-lstm-dynamic-decay-relative-classjson-pretrain":
        raise ValueError(
            f"resume checkpoint stage={ckpt.get('stage')} is not F1-v5-support-conditioned-lstm-dynamic-decay-relative-classjson-pretrain; "
            "older incompatible F1 heads are intentionally not resumed into the support-conditioned LSTM."
        )
    state = ckpt.get("temporal_decay_head")
    if state is None:
        raise KeyError("F1-v5 checkpoint lacks temporal_decay_head")
    decay_head.load_state_dict(state, strict=True)
    if "optimizer" in ckpt:
        optimizer.load_state_dict(ckpt["optimizer"])
    if "scheduler" in ckpt:
        scheduler.load_state_dict(ckpt["scheduler"])
    return int(ckpt.get("epoch", 0))


