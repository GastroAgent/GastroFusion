class MetricSetEncoder(nn.Module):
    """Permutation-invariant encoder for a set of class-level Metric representations.

    Input shape: (..., M, D), where M is the number of candidate classes.
    The encoder does not concatenate class members.  It learns an element embedding,
    then combines first-order set mean and dispersion through additive projections.
    Therefore class order cannot change the resulting context.
    """

    def __init__(self, input_dim: int, output_dim: int, dropout: float = 0.10) -> None:
        super().__init__()
        self.input_dim = int(input_dim)
        self.output_dim = int(output_dim)
        self.norm = nn.LayerNorm(self.input_dim)
        self.phi = nn.Sequential(
            nn.Linear(self.input_dim, self.output_dim),
            nn.GELU(),
            nn.Dropout(float(dropout)),
            nn.Linear(self.output_dim, self.output_dim),
            nn.GELU(),
        )
        self.mean_proj = nn.Linear(self.output_dim, self.output_dim, bias=False)
        self.disp_proj = nn.Linear(self.output_dim, self.output_dim, bias=False)
        self.out_norm = nn.LayerNorm(self.output_dim)

    def forward(self, values: torch.Tensor) -> torch.Tensor:
        if values.ndim < 2 or values.shape[-1] != self.input_dim:
            raise ValueError(
                f"MetricSetEncoder expects (...,M,{self.input_dim}), got {tuple(values.shape)}"
            )
        h = self.phi(self.norm(values.float()))
        mean = h.mean(dim=-2)
        disp = (h - mean.unsqueeze(-2)).square().mean(dim=-2).clamp_min(0.0).sqrt()
        out = self.mean_proj(mean) + self.disp_proj(disp)
        return F.gelu(self.out_norm(out))


class ConditionalLSTMCell(nn.Module):
    """LSTM cell whose gates receive an independent observable condition stream.

    x_t        : current Metric trajectory representation
    h_{t-1}    : recurrent visible state
    c_{t-1}    : long-term memory (initialized from Support Metric context)
    condition  : statistics + explicit time embedding

    Statistics/time are NOT concatenated to x_t.  They directly condition all four
    LSTM gate pre-activations through a separate learned projection.
    """

    def __init__(self, input_dim: int, hidden_dim: int, condition_dim: int) -> None:
        super().__init__()
        self.input_dim = int(input_dim)
        self.hidden_dim = int(hidden_dim)
        self.condition_dim = int(condition_dim)
        self.x_proj = nn.Linear(self.input_dim, 4 * self.hidden_dim, bias=True)
        self.h_proj = nn.Linear(self.hidden_dim, 4 * self.hidden_dim, bias=False)
        self.cond_proj = nn.Linear(self.condition_dim, 4 * self.hidden_dim, bias=False)
        self.gate_norm = nn.LayerNorm(4 * self.hidden_dim)

        # Encourage stable memory retention at initialization.
        with torch.no_grad():
            self.x_proj.bias.zero_()
            self.x_proj.bias[self.hidden_dim : 2 * self.hidden_dim].fill_(1.0)

    def forward(
        self,
        x_t: torch.Tensor,
        h_prev: torch.Tensor,
        c_prev: torch.Tensor,
        condition_t: torch.Tensor,
    ) -> tuple[torch.Tensor, torch.Tensor]:
        gates = self.x_proj(x_t) + self.h_proj(h_prev) + self.cond_proj(condition_t)
        gates = self.gate_norm(gates)
        i_t, f_t, g_t, o_t = gates.chunk(4, dim=-1)
        i_t = torch.sigmoid(i_t)
        f_t = torch.sigmoid(f_t)
        g_t = torch.tanh(g_t)
        o_t = torch.sigmoid(o_t)
        c_t = f_t * c_prev + i_t * g_t
        h_t = o_t * torch.tanh(c_t)
        return h_t, c_t


class TemporalDecayHead(nn.Module):
    """Support-conditioned recurrent estimator of dynamic decay coefficients.

    The information routes are intentionally separated instead of simple concatenation:

      Support Metric class set -> support_set_encoder -> c0 (long-term reference memory)
      Direct query Metric       -> query_encoder       -> h0 (initial visible state)
      Current Flow-step Metric class set -> step_set_encoder -> x_t
      Observable statistics -> stat_encoder --+
      explicit t/T          -> time_encoder --+-> condition_t -> LSTM gates

    The conditional LSTM updates (h_t,c_t) sequentially and one shared nonlinear head
    maps h_t to gamma_t.  Final state weights are cumulative products of gamma_t, so
    w_0 >= ... >= w_T is guaranteed structurally.
    """

    def __init__(
        self,
        stat_feature_dim: int,
        repr_dim: int,
        hidden_dim: int = 64,
        set_dim: int = 64,
        condition_dim: int = 32,
        head_dropout: float = 0.10,
        gamma_min: float = 0.70,
        gamma_init: float = 0.95,
    ) -> None:
        super().__init__()
        if min(int(stat_feature_dim), int(repr_dim), int(hidden_dim), int(set_dim), int(condition_dim)) < 1:
            raise ValueError("all TemporalDecayHead dimensions must be >=1")
        if not 0.0 <= float(head_dropout) < 1.0:
            raise ValueError("head_dropout must be in [0,1)")
        if not 0.0 < float(gamma_min) < float(gamma_init) < 1.0:
            raise ValueError("require 0 < gamma_min < gamma_init < 1")

        self.stat_feature_dim = int(stat_feature_dim)
        self.repr_dim = int(repr_dim)
        self.hidden_dim = int(hidden_dim)
        self.set_dim = int(set_dim)
        self.condition_dim = int(condition_dim)
        self.gamma_min = float(gamma_min)
        self.head_dropout = float(head_dropout)

        self.support_set_encoder = MetricSetEncoder(
            self.repr_dim, self.set_dim, dropout=self.head_dropout
        )
        self.step_set_encoder = MetricSetEncoder(
            self.repr_dim, self.set_dim, dropout=self.head_dropout
        )

        self.support_to_cell = nn.Sequential(
            nn.Linear(self.set_dim, self.hidden_dim),
            nn.Tanh(),
        )
        self.query_encoder = nn.Sequential(
            nn.LayerNorm(self.repr_dim),
            nn.Linear(self.repr_dim, self.hidden_dim),
            nn.GELU(),
            nn.Dropout(self.head_dropout),
            nn.Linear(self.hidden_dim, self.hidden_dim),
            nn.Tanh(),
        )
        self.step_to_input = nn.Sequential(
            nn.Linear(self.set_dim, self.hidden_dim),
            nn.GELU(),
            nn.Dropout(self.head_dropout),
        )

        self.stat_encoder = nn.Sequential(
            nn.LayerNorm(self.stat_feature_dim),
            nn.Linear(self.stat_feature_dim, self.condition_dim),
            nn.GELU(),
            nn.Dropout(self.head_dropout),
            nn.Linear(self.condition_dim, self.condition_dim),
        )
        self.time_encoder = nn.Sequential(
            nn.Linear(1, self.condition_dim),
            nn.GELU(),
            nn.Linear(self.condition_dim, self.condition_dim),
        )
        self.condition_norm = nn.LayerNorm(self.condition_dim)

        self.temporal = ConditionalLSTMCell(
            input_dim=self.hidden_dim,
            hidden_dim=self.hidden_dim,
            condition_dim=self.condition_dim,
        )

        self.output_norm = nn.LayerNorm(self.hidden_dim)
        self.decay_mlp = nn.Sequential(
            nn.Linear(self.hidden_dim, self.hidden_dim),
            nn.GELU(),
            nn.Dropout(self.head_dropout),
            nn.Linear(self.hidden_dim, 1),
        )

        p = (float(gamma_init) - self.gamma_min) / (1.0 - self.gamma_min)
        p = min(max(p, 1e-6), 1.0 - 1e-6)
        init_bias = math.log(p / (1.0 - p))
        final = self.decay_mlp[-1]
        assert isinstance(final, nn.Linear)
        nn.init.normal_(final.weight, mean=0.0, std=1e-3)
        nn.init.constant_(final.bias, init_bias)

    def logits_to_gamma(self, raw_logits: torch.Tensor) -> torch.Tensor:
        return self.gamma_min + (1.0 - self.gamma_min) * torch.sigmoid(raw_logits.float())

    def forward(
        self,
        stat_features: torch.Tensor,
        support_class_repr: torch.Tensor,
        direct_query_repr: torch.Tensor,
        step_class_repr: torch.Tensor,
    ) -> tuple[torch.Tensor, torch.Tensor]:
        """Args:
            stat_features:      (Q,T,F)
            support_class_repr: (N,D) or (Q,N,D), class-level support prototypes
            direct_query_repr:  (Q,D), direct-query Metric representation
            step_class_repr:    (Q,T,N,D), candidate-class Flow-state representations
        """
        if stat_features.ndim != 3:
            raise ValueError(f"stat_features must be (Q,T,F), got {tuple(stat_features.shape)}")
        q, t_steps, fdim = stat_features.shape
        if fdim != self.stat_feature_dim:
            raise ValueError(f"stat feature dim={fdim}, expected {self.stat_feature_dim}")
        if direct_query_repr.shape != (q, self.repr_dim):
            raise ValueError(
                f"direct_query_repr={tuple(direct_query_repr.shape)}, expected {(q, self.repr_dim)}"
            )
        if step_class_repr.ndim != 4 or step_class_repr.shape[:2] != (q, t_steps):
            raise ValueError(
                f"step_class_repr must be (Q,T,N,D), got {tuple(step_class_repr.shape)}"
            )
        if step_class_repr.shape[-1] != self.repr_dim:
            raise ValueError("step representation dimension mismatch")

        if support_class_repr.ndim == 2:
            if support_class_repr.shape[-1] != self.repr_dim:
                raise ValueError("support representation dimension mismatch")
            support_ctx = self.support_set_encoder(support_class_repr).unsqueeze(0).expand(q, -1)
        elif support_class_repr.ndim == 3:
            if support_class_repr.shape[0] != q or support_class_repr.shape[-1] != self.repr_dim:
                raise ValueError("batched support representation shape mismatch")
            support_ctx = self.support_set_encoder(support_class_repr)
        else:
            raise ValueError("support_class_repr must be (N,D) or (Q,N,D)")

        # Semantic role separation: Support -> c0, Direct query -> h0.
        c_t = self.support_to_cell(support_ctx.float())
        h_t = self.query_encoder(direct_query_repr.float())

        step_ctx = self.step_set_encoder(step_class_repr.float())  # (Q,T,set_dim)
        step_x = self.step_to_input(step_ctx)                      # (Q,T,H)

        stat_cond = self.stat_encoder(stat_features.float())
        tau = torch.arange(
            1, t_steps + 1, device=stat_features.device, dtype=torch.float32
        ).view(1, t_steps, 1).expand(q, -1, -1) / float(max(t_steps, 1))
        time_cond = self.time_encoder(tau)
        condition = self.condition_norm(stat_cond + time_cond)

        raw_steps = []
        for j in range(t_steps):
            h_t, c_t = self.temporal(step_x[:, j], h_t, c_t, condition[:, j])
            raw_steps.append(self.decay_mlp(self.output_norm(h_t)).squeeze(-1))
        raw_logits = torch.stack(raw_steps, dim=1)
        gamma = self.logits_to_gamma(raw_logits)
        return raw_logits, gamma


def shot_softmin_class_scores(
    distances: torch.Tensor,
    *,
    shot_tau: torch.Tensor,
    cls_tau: torch.Tensor,
) -> tuple[torch.Tensor, torch.Tensor]:
    """Pair distances -> per-step class scores/logits.

    Args:
        distances: (Q, N, K, V), V=T+1 and index 0 is Direct.
    Returns:
        class_scores: (Q,V,N), lower is better.
        step_logits:  (Q,V,N), higher is better.
    """
    if distances.ndim != 4:
        raise ValueError(f"distances must be (Q,N,K,V), got {tuple(distances.shape)}")
    q, n, k, v = distances.shape
    x = distances.permute(0, 3, 1, 2).contiguous()  # (Q,V,N,K)
    tau_s = shot_tau.to(x.device).float().clamp_min(1e-8)
    scores = -tau_s * (
        torch.logsumexp(-x.float() / tau_s, dim=-1) - math.log(float(k))
    )
    tau_c = cls_tau.to(x.device).float().clamp_min(1e-8)
    logits = -scores / tau_c
    return scores, logits


def build_observable_step_features(
    distances: torch.Tensor,
    step_logits: torch.Tensor,
    direct_support_logits: torch.Tensor,
    *,
    eps: float,
    ratio_clip: float,
) -> torch.Tensor:
    """Build causal deployable statistics for each transition 0->1 ... T-1->T.

    No GT, CE, correctness, oracle, or future-state feature is used.  The direct
    classification anchor is always computed from D(z0, real support), independent
    of whether the learned trajectory branch is step_to_support or step_to_last.
    """
    if distances.ndim != 4 or step_logits.ndim != 3 or direct_support_logits.ndim != 2:
        raise ValueError("invalid distance/logit shape")
    q, n, k, v = distances.shape
    if step_logits.shape != (q, v, n):
        raise ValueError("step_logits shape mismatch")
    if direct_support_logits.shape != (q, n):
        raise ValueError("direct_support_logits shape mismatch")
    t_steps = v - 1
    if t_steps < 1:
        raise ValueError("trajectory must contain at least one post step")

    d0 = distances[..., 0].float().clamp_min(float(eps))
    ratio = (distances[..., 1:].float() / d0.unsqueeze(-1)).clamp(
        min=0.0, max=float(ratio_clip)
    )
    pair_ratio_mean = ratio.mean(dim=(1, 2))
    pair_ratio_std = ratio.std(dim=(1, 2), unbiased=False)

    delta_rel = (
        (distances[..., 1:].float() - distances[..., :-1].float())
        / d0.unsqueeze(-1)
    ).clamp(min=-float(ratio_clip), max=float(ratio_clip))
    pair_delta_mean = delta_rel.mean(dim=(1, 2))
    pair_delta_std = delta_rel.std(dim=(1, 2), unbiased=False)
    mono_rel = F.relu(delta_rel)

    pair_prefix_area = []
    pair_prefix_mono = []
    for j in range(t_steps):
        pair_prefix_area.append(ratio[..., : j + 1].mean(dim=(1, 2, 3)))
        pair_prefix_mono.append(mono_rel[..., : j + 1].mean(dim=(1, 2, 3)))
    pair_prefix_area = torch.stack(pair_prefix_area, dim=1)
    pair_prefix_mono = torch.stack(pair_prefix_mono, dim=1)

    probs = F.softmax(step_logits.float(), dim=-1)
    p_safe = probs.clamp_min(1e-12)
    if n >= 2:
        top2 = probs.topk(k=2, dim=-1)
        margin = top2.values[..., 0] - top2.values[..., 1]
        top_indices = top2.indices
    else:
        margin = probs[..., 0]
        top_indices = torch.zeros(q, v, 2, device=probs.device, dtype=torch.long)

    entropy = -(p_safe * p_safe.log()).sum(dim=-1)
    entropy = entropy / max(math.log(float(n)), 1e-8)
    pred = probs.argmax(dim=-1)

    direct_probs = F.softmax(direct_support_logits.float(), dim=-1)
    direct_safe = direct_probs.clamp_min(1e-12)
    if n >= 2:
        dtop2 = direct_probs.topk(k=2, dim=-1).values
        direct_margin_scalar = dtop2[:, 0] - dtop2[:, 1]
    else:
        direct_margin_scalar = direct_probs[:, 0]
    direct_entropy_scalar = -(direct_safe * direct_safe.log()).sum(dim=-1)
    direct_entropy_scalar = direct_entropy_scalar / max(math.log(float(n)), 1e-8)
    direct_pred = direct_probs.argmax(dim=-1)

    direct_margin = direct_margin_scalar[:, None].expand(-1, t_steps)
    trajectory_state0_margin = margin[:, 0:1].expand(-1, t_steps)
    current_margin = margin[:, 1:]
    delta_margin = margin[:, 1:] - margin[:, :-1]

    direct_entropy = direct_entropy_scalar[:, None].expand(-1, t_steps)
    trajectory_state0_entropy = entropy[:, 0:1].expand(-1, t_steps)
    current_entropy = entropy[:, 1:]
    delta_entropy = entropy[:, 1:] - entropy[:, :-1]

    agree_previous = pred[:, 1:].eq(pred[:, :-1]).float()
    agree_direct = pred[:, 1:].eq(direct_pred[:, None]).float()
    flip_previous = 1.0 - agree_previous

    prev_p = probs[:, :-1]
    curr_p = probs[:, 1:]
    probability_shift = (curr_p - prev_p).abs().mean(dim=-1)
    mix = (0.5 * (prev_p + curr_p)).clamp_min(1e-12)
    prev_safe = prev_p.clamp_min(1e-12)
    curr_safe = curr_p.clamp_min(1e-12)
    js_shift = 0.5 * (
        (prev_safe * (prev_safe.log() - mix.log())).sum(dim=-1)
        + (curr_safe * (curr_safe.log() - mix.log())).sum(dim=-1)
    ) / math.log(2.0)

    delta2_margin = torch.zeros_like(delta_margin)
    delta2_entropy = torch.zeros_like(delta_entropy)
    if t_steps > 1:
        delta2_margin[:, 1:] = delta_margin[:, 1:] - delta_margin[:, :-1]
        delta2_entropy[:, 1:] = delta_entropy[:, 1:] - delta_entropy[:, :-1]

    denom = torch.arange(
        1, t_steps + 1, device=distances.device, dtype=torch.float32
    ).view(1, t_steps)
    prefix_flip_rate = flip_previous.cumsum(dim=1) / denom
    prefix_shift_mean = probability_shift.cumsum(dim=1) / denom
    prefix_shift_second = probability_shift.square().cumsum(dim=1) / denom
    prefix_shift_std = (
        prefix_shift_second - prefix_shift_mean.square()
    ).clamp_min(0.0).sqrt()

    # K-shot consistency of currently ranked classes at each post state.
    state_dist = distances[..., 1:].permute(0, 3, 1, 2).contiguous()  # Q,T,N,K
    if n >= 2:
        ranked = top_indices[:, 1:, :2]  # Q,T,2
    else:
        ranked = torch.zeros(q, t_steps, 2, device=distances.device, dtype=torch.long)
    gather_idx = ranked.unsqueeze(-1).expand(-1, -1, -1, k)
    ranked_shots = state_dist.gather(dim=2, index=gather_idx)  # Q,T,2,K
    shot_mean = ranked_shots.mean(dim=-1).abs().clamp_min(float(eps))
    shot_std = ranked_shots.std(dim=-1, unbiased=False)
    shot_cv = (shot_std / shot_mean).clamp(max=float(ratio_clip))
    top1_shot_cv = shot_cv[..., 0]
    top2_shot_cv = shot_cv[..., 1]

    features = torch.stack(
        [
            pair_ratio_mean,
            pair_ratio_std,
            pair_prefix_area,
            pair_prefix_mono,
            pair_delta_mean,
            pair_delta_std,
            direct_margin,
            trajectory_state0_margin,
            current_margin,
            delta_margin,
            direct_entropy,
            trajectory_state0_entropy,
            current_entropy,
            delta_entropy,
            agree_previous,
            agree_direct,
            probability_shift,
            js_shift,
            delta2_margin,
            delta2_entropy,
            flip_previous,
            prefix_flip_rate,
            prefix_shift_mean,
            prefix_shift_std,
            top1_shot_cv,
            top2_shot_cv,
        ],
        dim=-1,
    )
    if features.shape[-1] != len(FEATURE_NAMES):
        raise AssertionError(
            f"feature construction/name mismatch: {features.shape[-1]} vs {len(FEATURE_NAMES)}"
        )
    if not torch.isfinite(features).all():
        raise RuntimeError("non-finite support-conditioned F1 statistics detected")
    return features


def decay_gamma_to_state_weights(gamma: torch.Tensor) -> torch.Tensor:
    """Local retention coefficients -> normalized monotonic state weights.

    gamma shape (..., T), each in (0,1].
    Returns (..., T+1) for z_0 ... z_T.

        u_0 = 1
        u_t = prod_{i<=t} gamma_i
        w_t = u_t / sum_j u_j

    Thus w_0 >= w_1 >= ... >= w_T and sum_t w_t = 1 exactly (up to fp error).
    """
    if gamma.ndim < 1:
        raise ValueError("gamma must have at least one dimension")
    if not torch.isfinite(gamma).all():
        raise RuntimeError("non-finite gamma detected")
    if (gamma <= 0).any() or (gamma > 1.0 + 1e-6).any():
        raise ValueError("gamma must lie in (0,1]")

    cumulative = torch.cumprod(gamma.float(), dim=-1)
    one = torch.ones_like(cumulative[..., :1])
    unnormalized = torch.cat([one, cumulative], dim=-1)
    weights = unnormalized / unnormalized.sum(dim=-1, keepdim=True).clamp_min(1e-12)
    return weights


def weighted_pair_class_logits(
    distances: torch.Tensor,
    state_weights: torch.Tensor,
    *,
    shot_tau: torch.Tensor,
    cls_tau: torch.Tensor,
) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    """Temporal weighted pair distances -> frozen M2 K-shot soft-min class logits.

    distances:     (Q,N,K,V)
    state_weights: (Q,V)
    Returns:
        pair_score:  (Q,N,K)
        class_score: (Q,N), lower is better
        logits:      (Q,N), higher is better
    """
    if distances.ndim != 4 or state_weights.ndim != 2:
        raise ValueError("distances must be (Q,N,K,V), state_weights must be (Q,V)")
    q, n, k, v = distances.shape
    if state_weights.shape != (q, v):
        raise ValueError(
            f"state_weights={tuple(state_weights.shape)} incompatible with distances={tuple(distances.shape)}"
        )
    pair_score = (distances.float() * state_weights[:, None, None, :].float()).sum(dim=-1)
    tau_s = shot_tau.to(pair_score.device).float().clamp_min(1e-8)
    class_score = -tau_s * (
        torch.logsumexp(-pair_score / tau_s, dim=-1) - math.log(float(k))
    )
    tau_c = cls_tau.to(pair_score.device).float().clamp_min(1e-8)
    logits = -class_score / tau_c
    return pair_score, class_score, logits


def group_weighted_class_logits(
    distances: torch.Tensor,
    group_state_weights: torch.Tensor,
    *,
    shot_tau: torch.Tensor,
    cls_tau: torch.Tensor,
) -> torch.Tensor:
    """Vectorized group policies.

    distances:           (Q,N,K,V)
    group_state_weights: (Q,G,V)
    returns logits:      (Q,G,N)
    """
    if distances.ndim != 4 or group_state_weights.ndim != 3:
        raise ValueError("invalid group weighted score shapes")
    q, n, k, v = distances.shape
    if group_state_weights.shape[0] != q or group_state_weights.shape[-1] != v:
        raise ValueError("group_state_weights incompatible with distances")
    pair_score = torch.einsum(
        "qnkv,qgv->qgnk", distances.float(), group_state_weights.float()
    )
    tau_s = shot_tau.to(pair_score.device).float().clamp_min(1e-8)
    class_score = -tau_s * (
        torch.logsumexp(-pair_score / tau_s, dim=-1) - math.log(float(k))
    )
    tau_c = cls_tau.to(pair_score.device).float().clamp_min(1e-8)
    return -class_score / tau_c


def direct_support_logits(
    support_distances: torch.Tensor,
    *,
    shot_tau: torch.Tensor,
    cls_tau: torch.Tensor,
) -> torch.Tensor:
    """Frozen M2 Direct logits from D(z_0, support), independent of score mode."""
    if support_distances.ndim != 4:
        raise ValueError("support_distances must be (Q,N,K,V)")
    pair = support_distances[..., 0].float()
    k = pair.shape[-1]
    tau_s = shot_tau.to(pair.device).float().clamp_min(1e-8)
    score = -tau_s * (
        torch.logsumexp(-pair / tau_s, dim=-1) - math.log(float(k))
    )
    tau_c = cls_tau.to(pair.device).float().clamp_min(1e-8)
    return -score / tau_c


def decay_smoothness_loss(gamma: torch.Tensor) -> torch.Tensor:
    """Mild smoothness on LOCAL decay rate r_t=-log(gamma_t), not on final weights."""
    if gamma.shape[-1] <= 1:
        return gamma.new_zeros(())
    rate = -gamma.float().clamp_min(1e-8).log()
    return (rate[..., 1:] - rate[..., :-1]).square().mean()


def relative_sigma_for_epoch(args, epoch_index: int) -> float:
    """Cosine annealing of exploration std after a pure-CE warmup."""
    if epoch_index < int(args.relative_warmup_epochs):
        return 0.0
    if float(args.lambda_relative) <= 0.0:
        return 0.0
    remaining = max(int(args.epochs) - int(args.relative_warmup_epochs), 1)
    pos = epoch_index - int(args.relative_warmup_epochs)
    if remaining <= 1:
        progress = 1.0
    else:
        progress = min(max(pos / float(remaining - 1), 0.0), 1.0)
    c = 0.5 * (1.0 + math.cos(math.pi * progress))
    return float(args.relative_sigma_end) + (
        float(args.relative_sigma_start) - float(args.relative_sigma_end)
    ) * c


def group_relative_decay_loss(
    *,
    decay_head: TemporalDecayHead,
    raw_logits: torch.Tensor,
    deterministic_gamma: torch.Tensor,
    deterministic_logits: torch.Tensor,
    selected_distances: torch.Tensor,
    direct_logits: torch.Tensor,
    target: torch.Tensor,
    shot_tau: torch.Tensor,
    cls_tau: torch.Tensor,
    sigma: float,
    args,
) -> tuple[torch.Tensor, dict[str, float]]:
    """Antithetic group-relative exploration around current decay logits.

    Reward = CE_direct - CE_policy.  The direct term is common within a query, so
    group-relative ranking is equivalently driven by lower policy CE.  Rewards are
    standardized within each query.  The resulting reward-correlated perturbation
    direction is distilled back into the deterministic raw logits with Smooth-L1.

    This is intentionally GRPO-inspired / ES-style rather than a literal PPO clone:
    the action is a tiny continuous T-dimensional decay schedule and the underlying
    classification path is differentiable, so exact CE gradients are retained too.
    """
    zero = raw_logits.new_zeros(())
    stats = {
        "sigma": float(sigma),
        "reward_std": 0.0,
        "best_gain_over_current_ce": 0.0,
        "mean_abs_delta_gamma": 0.0,
        "active_fraction": 0.0,
    }
    if sigma <= 0.0 or float(args.lambda_relative) <= 0.0:
        return zero, stats

    g = int(args.relative_group_size)
    if g < 2 or g % 2 != 0:
        raise ValueError("relative_group_size must be an even integer >=2")

    q, t = raw_logits.shape
    half = g // 2
    with torch.no_grad():
        eps_half = torch.randn(q, half, t, device=raw_logits.device, dtype=torch.float32)
        eps = torch.cat([eps_half, -eps_half], dim=1)  # (Q,G,T)
        perturbed_raw = raw_logits.detach().unsqueeze(1) + float(sigma) * eps
        perturbed_gamma = unwrap_model(decay_head).logits_to_gamma(perturbed_raw)
        group_weights = decay_gamma_to_state_weights(perturbed_gamma)
        group_logits = group_weighted_class_logits(
            selected_distances,
            group_weights,
            shot_tau=shot_tau,
            cls_tau=cls_tau,
        )

        n = group_logits.shape[-1]
        target_group = target[:, None].expand(q, g).reshape(-1)
        sample_ce = F.cross_entropy(
            group_logits.reshape(q * g, n).float(),
            target_group,
            reduction="none",
        ).reshape(q, g)
        direct_ce = F.cross_entropy(direct_logits.float(), target, reduction="none")
        current_ce = F.cross_entropy(
            deterministic_logits.float(), target, reduction="none"
        )
        reward = direct_ce[:, None] - sample_ce

        centered = reward - reward.mean(dim=1, keepdim=True)
        reward_std = reward.std(dim=1, unbiased=False, keepdim=True)
        active = reward_std.squeeze(1) >= float(args.relative_min_reward_std)
        advantage = centered / reward_std.clamp_min(float(args.relative_min_reward_std))
        advantage = advantage.clamp(
            -float(args.relative_adv_clip), float(args.relative_adv_clip)
        )
        advantage = advantage * active[:, None].float()

        # Relative ES direction.  Antithetic sampling cancels much of the noise.
        direction = (advantage.unsqueeze(-1) * eps).mean(dim=1)
        target_raw = raw_logits.detach() + float(args.relative_target_step) * direction

        best_ce = sample_ce.min(dim=1).values
        best_gain = current_ce - best_ce
        base_gamma = deterministic_gamma.detach().unsqueeze(1)
        mean_abs_delta_gamma = (perturbed_gamma - base_gamma).abs().mean()

        stats = {
            "sigma": float(sigma),
            "reward_std": float(reward_std.mean().item()),
            "best_gain_over_current_ce": float(best_gain.mean().item()),
            "mean_abs_delta_gamma": float(mean_abs_delta_gamma.item()),
            "active_fraction": float(active.float().mean().item()),
        }

    relative_loss = F.smooth_l1_loss(raw_logits.float(), target_raw.float())
    return relative_loss, stats


