"""F1-v5 ImageNet/class-JSON pretraining: monotonic dynamic-decay trajectory weighting with relative exploration.

Core principle
--------------
The frozen RAE / M2 MetricEncoder / Flow pipeline produces a candidate-conditioned
trajectory z_0 ... z_T and the corresponding per-pair distance trajectory.
F1-v5 does NOT predict unconstrained per-step weights and does NOT use residual gates.
Instead, a support-conditioned causal LSTM predicts one dynamic information-retention coefficient
per transition:

    gamma_t = gamma_min + (1-gamma_min) * sigmoid(a_t),   a_t = SharedMLP(h_t)

The same nonlinear decay head is reused at every step while the conditional LSTM hidden state h_t
changes with support-conditioned trajectory history.  State weights are generated by cumulative retention:

    u_0 = 1
    u_t = prod_{i=1..t} gamma_i
    w_t = u_t / sum_j u_j

Therefore, for every query and every forward pass:

    w_0 >= w_1 >= ... >= w_T > 0,   sum_t w_t = 1.

This strictly encodes the empirical prior that later Flow states generally contain
less discriminative classification signal, while allowing the decay RATE to change
adaptively along the trajectory.  Constant gamma_t reduces exactly to the fixed
exponential decay used in validation; gamma_t -> 1 approaches the uniform mean.

Trajectory score modes
----------------------
--trajectory_score_mode step_to_support:
    sum_t w_t D(z_t, support)

--trajectory_score_mode step_to_last:
    sum_t w_t D(z_t, z_T)

The weighted pair score is formed BEFORE frozen M2 K-shot soft-min aggregation.
The Direct baseline always remains D(z_0, support).

Optimization
------------
Only the tiny TemporalDecayHead is trainable.  The main objective is the exact,
differentiable final classification CE.  To supplement this local gradient with
comparative exploration, training optionally performs antithetic group-relative
perturbations around the current decay logits a_t:

    a^(k) = a + sigma * epsilon^(k), with paired +epsilon / -epsilon.

Each perturbed decay schedule is scored using the already-computed frozen trajectory;
no extra Flow generation is required.  Reward is classification gain relative to
Direct (Direct CE - perturbed CE), group-standardized into a relative advantage.
A small ES/CEM-style distillation target moves the deterministic logits toward the
reward-correlated perturbation direction.  sigma is annealed across epochs.

Train/val episodes are sampled online from class-named JSON pools. Training is stochastic; validation/inference is deterministic and uses only:

    support/step Metric + statistics/time -> conditional LSTM -> gamma_t -> monotonic w_t -> weighted score
    -> K-shot soft-min -> prediction.

GT is used only by training losses/rewards and is never an F1 input feature.
"""

