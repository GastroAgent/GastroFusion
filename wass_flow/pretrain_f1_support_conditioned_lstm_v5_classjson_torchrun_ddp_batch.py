class FrozenFlowRuntime:
    """Frozen DiT + frozen target visual encoder for candidate-conditioned paths."""

    DATASET_MEAN = (0.3464, 0.2280, 0.2228)
    DATASET_STD = (0.2520, 0.2128, 0.2093)

    def __init__(
        self,
        *,
        project_root: str,
        checkpoint: str,
        device: torch.device,
        dit_variant: str,
        num_classes: int,
        image_size: int,
        use_ema: bool,
        hint_signal_ratio: Optional[float],
        allow_condition_mismatch: bool,
        amp: bool,
    ) -> None:
        if device.type != "cuda":
            raise RuntimeError("DiT trajectory generation requires a CUDA device")

        self.project_root = str(Path(project_root).resolve())
        if self.project_root not in sys.path:
            sys.path.insert(0, self.project_root)
        self.device = device
        self.amp = bool(amp)
        self.image_size = int(image_size)

        from flow_models.dit_rae import create_dit_rae
        from timm.models.vision_transformer import VisionTransformer

        ckpt = _torch_load(checkpoint, "cpu")
        if not isinstance(ckpt, dict):
            raise ValueError("DiT checkpoint must be a dict checkpoint")

        self.condition_config = ckpt.get("condition_config") or {}
        saved_mode = self.condition_config.get("condition_mode")
        saved_size = self.condition_config.get("image_size")
        mismatch = (
            saved_mode != "vision_hint_v1"
            or (saved_size is not None and int(saved_size) != self.image_size)
        )
        if mismatch and not allow_condition_mismatch:
            raise RuntimeError(
                "DiT checkpoint condition_config is not V1-compatible.\n"
                f"saved={self.condition_config}\nrequested image_size={self.image_size}\n"
                "Use --allow_condition_mismatch only for an intentional ablation."
            )

        self.hint_signal_ratio = float(
            self.condition_config.get("hint_signal_ratio", 0.10)
            if hint_signal_ratio is None else hint_signal_ratio
        )
        if not 0.0 <= self.hint_signal_ratio <= 1.0:
            raise ValueError("hint_signal_ratio must be in [0,1]")

        dit = create_dit_rae(
            variant=dit_variant,
            rae_latent_dim=1024,
            rae_spatial_size=16,
            cross_attn_dim=768,
            num_classes=num_classes,
            use_cross_attention=True,
        )
        if use_ema and isinstance(ckpt.get("ema_model"), dict):
            dit_state = ckpt["ema_model"]
            self.loaded_dit_key = "ema_model"
        elif isinstance(ckpt.get("dit_model"), dict):
            dit_state = ckpt["dit_model"]
            self.loaded_dit_key = "dit_model"
        else:
            dit_state = ckpt
            self.loaded_dit_key = "checkpoint_root"

        missing, unexpected = dit.load_state_dict(dit_state, strict=False)
        if missing:
            print(f"[F1-v3][WARN] DiT missing keys: {missing[:12]}")
        if unexpected:
            print(f"[F1-v3][WARN] DiT unexpected keys: {unexpected[:12]}")
        dit = dit.to(self.device).eval()
        dit.device = self.device
        for p in dit.parameters():
            p.requires_grad_(False)
        self.dit = dit

        vision = VisionTransformer(
            patch_size=16,
            embed_dim=768,
            depth=12,
            num_heads=12,
            mlp_ratio=4,
            qkv_bias=False,
            norm_layer=partial(nn.LayerNorm, eps=1e-6),
        ).eval()
        endovit_path = os.path.join(
            self.project_root, "flow_matcher_otcfm/EndoViT/pytorch_model.bin"
        )
        vision.load_state_dict(
            torch.load(endovit_path, map_location="cpu", weights_only=False), strict=False
        )
        if isinstance(ckpt.get("vision_model"), dict):
            vision.load_state_dict(ckpt["vision_model"], strict=False)
        vision = vision.to(self.device).eval()
        vision.device = self.device
        for p in vision.parameters():
            p.requires_grad_(False)
        self.vision = vision
        del ckpt

    @torch.no_grad()
    def encode_target_vision(self, support_images_01: torch.Tensor) -> torch.Tensor:
        x = support_images_01.to(self.device, non_blocking=True).float()
        x = F.interpolate(x, size=(224, 224), mode="bilinear", align_corners=False)
        mean = torch.tensor(self.DATASET_MEAN, device=self.device, dtype=x.dtype).view(1, 3, 1, 1)
        std = torch.tensor(self.DATASET_STD, device=self.device, dtype=x.dtype).view(1, 3, 1, 1)
        x = (x - mean) / std
        with torch.autocast(device_type="cuda", dtype=torch.float16, enabled=self.amp):
            out = self.vision.forward_features(x)
        return out.float()

    @torch.no_grad()
    def build_hint(
        self,
        support_images_01: torch.Tensor,
        *,
        stochastic: bool,
        pure_noise: bool,
        seed: Optional[int] = None,
    ) -> torch.Tensor:
        x = support_images_01.to(self.device, non_blocking=True).float()
        gray = (
            0.2989 * x[:, 0:1]
            + 0.5870 * x[:, 1:2]
            + 0.1140 * x[:, 2:3]
        ).repeat(1, 3, 1, 1)
        gray = gray * 2.0 - 1.0

        if seed is None:
            noise = torch.randn_like(gray) if stochastic or pure_noise else torch.zeros_like(gray)
        else:
            # Generate deterministic validation noise on CPU, then transfer.
            g = torch.Generator(device="cpu")
            g.manual_seed(int(seed))
            noise = torch.randn(gray.shape, generator=g, dtype=torch.float32).to(self.device)
            if not (stochastic or pure_noise):
                noise.zero_()

        if pure_noise:
            return noise
        alpha = self.hint_signal_ratio
        return alpha * gray + math.sqrt(max(1.0 - alpha * alpha, 0.0)) * noise

    @torch.no_grad()
    def generate_post_states(
        self,
        query_z: torch.Tensor,
        *,
        target_vision: torch.Tensor,
        hint: torch.Tensor,
        num_steps: int,
        solver: str,
    ) -> torch.Tensor:
        """Return predicted post-step states only, shape (B,T,1024,16,16)."""
        if num_steps < 1:
            raise ValueError("num_steps must be >=1")
        if solver not in {"euler", "heun"}:
            raise ValueError(f"unknown solver={solver}")

        x = query_z.to(self.device, non_blocking=True).float()
        target_vision = target_vision.to(self.device, non_blocking=True)
        hint = hint.to(self.device, non_blocking=True)
        patch = target_vision[:, 1:, :]
        cls = target_vision[:, 0, :]

        t_span = torch.linspace(0.0, 1.0, num_steps + 1, device=self.device)
        dt = float(1.0 / num_steps)
        post = []
        for i in range(num_steps):
            t = torch.full((x.shape[0],), float(t_span[i]), device=self.device)
            with torch.autocast(device_type="cuda", dtype=torch.float16, enabled=self.amp):
                dx1 = self.dit(
                    xt=x,
                    timestep=t,
                    class_labels=None,
                    encoder_hidden_states=patch,
                    hint=hint,
                    text_embeds=None,
                    image_embeds=cls,
                )["sample"]

                if solver == "euler":
                    x = x + dx1.float() * dt
                else:
                    x_euler = x + dx1.float() * dt
                    t_next = torch.full(
                        (x.shape[0],), float(t_span[i + 1]), device=self.device
                    )
                    dx2 = self.dit(
                        xt=x_euler,
                        timestep=t_next,
                        class_labels=None,
                        encoder_hidden_states=patch,
                        hint=hint,
                        text_embeds=None,
                        image_embeds=cls,
                    )["sample"]
                    x = x + 0.5 * (dx1.float() + dx2.float()) * dt
            post.append(x.detach())
        return torch.stack(post, dim=1)


